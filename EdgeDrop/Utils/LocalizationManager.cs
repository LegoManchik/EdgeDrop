namespace EdgeDrop;

public enum AppLanguage
{
    System,
    Russian,
    English
}

public static class LocalizationManager
{
    public static AppLanguage ConfiguredLanguage { get; private set; } = AppLanguage.System;
    public static AppLanguage EffectiveLanguage { get; private set; } = AppLanguage.Russian;
    public static event Action? LanguageChanged;

    public static void ApplyLanguage(AppLanguage language)
    {
        ConfiguredLanguage = language;

        if (language == AppLanguage.System)
        {
            string sys = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();

            EffectiveLanguage = (sys == "ru" || sys == "be" || sys == "kk" || sys == "uk")

                ? AppLanguage.Russian

                : AppLanguage.English;
        }

        else
        {
            EffectiveLanguage = language;
        }

        var res = WpfApp.Current?.Resources;

        if (res == null) return;

        var dict = EffectiveLanguage == AppLanguage.English ? GetEnglishDictionary() : GetRussianDictionary();

        foreach (var kv in dict)
        {
            res[kv.Key] = kv.Value;
        }

        LanguageChanged?.Invoke();
    }

    public static string GetString(string key, params object[] args)
    {
        var res = WpfApp.Current?.Resources;

        if (res != null && res.Contains(key) && res[key] is string val)
        {
            try
            {
                return args.Length > 0 ? string.Format(val, args) : val;
            }
            catch
            {
                return val;
            }
        }

        var fallback = EffectiveLanguage == AppLanguage.English ? GetEnglishDictionary() : GetRussianDictionary();

        if (fallback.TryGetValue(key, out var str))
        {
            try
            {
                return args.Length > 0 ? string.Format(str, args) : str;
            }
            catch
            {
                return str;
            }
        }

        return key;
    }

